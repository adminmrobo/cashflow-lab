# 10주차 예제 — (주)SG화학·서울(주) 2014년, 직접법과 간접법 (단위: 원, 유출은 음수)
import pandas as pd

손익 = pd.Series({"매출액": 2100, "매출원가": -1100, "보험료": -80, "급여": -550, "감가상각비": -80,
                "기타영업비용": -100, "이자비용": -30, "무형자산처분이익": 10})
잔액 = pd.DataFrame({"구분": ["자산", "자산", "자산", "부채", "부채"],
                   "기초": [230, 280, 10, 100, 20], "기말": [330, 220, 30, 140, 70]},
                  index=["매출채권", "상품재고", "선급보험료", "매입채무", "미지급급여"])
잔액["증감"] = 잔액["기말"] - 잔액["기초"]
d = 잔액["증감"]

# 직접법: 항목별 실제 현금
직접법 = pd.Series({
    "매출로부터의 현금수입": 손익["매출액"] - d["매출채권"],                          # 2,100 − 100
    "매입에 대한 현금지출": 손익["매출원가"] - d["상품재고"] + d["매입채무"],          # −1,100 + 60 + 40
    "급여 등 영업비용 지출": (손익["보험료"] - d["선급보험료"]) + (손익["급여"] + d["미지급급여"])
                            + 손익["기타영업비용"] + 손익["이자비용"],              # −100 − 500 − 100 − 30
})

# 간접법: 당기순이익에서 다섯 계단
당기순이익 = 손익.sum()
조정 = pd.Series(-잔액["증감"].where(잔액["구분"] == "자산", -잔액["증감"]))   # 자산 증가 −, 부채 증가 +
간접법 = pd.Series({"① 당기순이익": 당기순이익,
                  "② 감가상각비 가산": -손익["감가상각비"],
                  "③ 무형자산처분이익 차감": -손익["무형자산처분이익"],
                  "④ 영업 관련 자산·부채 변동": 조정.sum()})

세활동 = pd.Series({"영업활동": 직접법.sum(), "투자활동": 100 - 600, "재무활동": 500 - 70 - 50})
assert 직접법.sum() == 간접법.sum() == 270
assert 세활동.sum() == 400 - 250

print(직접법.to_string(), "\n합계", 직접법.sum())
print(간접법.to_string(), "\n합계", 간접법.sum())
print(세활동.to_string(), "\n현금의 증가", 세활동.sum(), "| 기초 250 → 기말", 250 + 세활동.sum())
