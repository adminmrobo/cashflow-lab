# 단위: 원 (표시는 억원). 유출은 음수.
import pandas as pd

억 = 100_000_000
def 억원(v):
    return round(v / 억, 1)

# ── 자료 1. 재무상태표 (영업 관련 계정만, 기초 = 제4기말, 기말 = 제5기말) ──
